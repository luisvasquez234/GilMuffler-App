function getIdioma() {
  return localStorage.getItem(IDIOMA_KEY) === "en" ? "en" : "es";
}

function setIdioma(idioma) {
  localStorage.setItem(IDIOMA_KEY, idioma === "en" ? "en" : "es");
  aplicarIdioma();
}

function t(clave, vars) {
  const idioma = getIdioma();
  let texto = (I18N[idioma] && I18N[idioma][clave]) || I18N.es[clave] || clave;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      texto = texto.replace(new RegExp("\\{\\{" + k + "\\}\\}", "g"), vars[k]);
    });
  }
  return texto;
}

function aplicarIdioma() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.documentElement.lang = getIdioma();
  document.querySelectorAll("[data-i18n-toggle-label]").forEach((el) => {
    el.textContent = getIdioma() === "es" ? "English" : "Español";
  });
}
